"""Keeps the relay's public name in step between the Bicep templates and the apps.

The apps build the relay address from the DNS suffix alone (app/ui/relay_endpoints.h), so the name Azure gives the container group has to
be exactly <label>.<region>.azurecontainer.io. Azure inserts a hash label (<label>.<hash>.<region>...) for every DNS name label reuse
policy except Unsecure, and a hashed name does not resolve for the apps. This test fails when a template or the app constants drift.

Offline and stdlib only. Run: python -m unittest discover -s infra/relay/tests -p "test_*.py" -v
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MAIN_BICEP = ROOT / "infra" / "relay" / "main.bicep"
RELAY_BICEP = ROOT / "infra" / "relay" / "modules" / "relay.bicep"
APP_HEADER = ROOT / "app" / "ui" / "relay_endpoints.h"


def read(path):
    return path.read_text(encoding="utf-8")


def bicep_default(text, name):
    match = re.search(rf"^param {name} (?:string|int) = '?([^'\n]+)'?\s*$", text, re.MULTILINE)
    assert match, f"param {name} has no default"
    return match.group(1)


def app_constant(name):
    match = re.search(rf"{name}\[\] = \"([^\"]+)\"|{name} = (\d+)", read(APP_HEADER))
    assert match, f"{name} not found in relay_endpoints.h"
    return match.group(1) or match.group(2)


class RelayNameTests(unittest.TestCase):
    def test_label_policy_keeps_the_fqdn_free_of_a_hash(self):
        self.assertEqual(bicep_default(read(RELAY_BICEP), "dnsNameLabelReusePolicy"), "Unsecure",
                         "any other reuse policy makes Azure insert a hash label the apps cannot build")

    def test_the_policy_is_passed_to_the_container_group(self):
        self.assertIn("autoGeneratedDomainNameLabelScope: dnsNameLabelReusePolicy", read(RELAY_BICEP))

    def test_main_does_not_override_the_policy(self):
        self.assertNotIn("dnsNameLabelReusePolicy", read(MAIN_BICEP))

    def test_app_constants_follow_the_bicep_defaults(self):
        main = read(MAIN_BICEP)
        self.assertEqual(app_constant("kRelayHostPrefix"), bicep_default(main, "namePrefix"))
        self.assertEqual(app_constant("kRelayAzureDomain"), bicep_default(main, "location") + ".azurecontainer.io")
        self.assertEqual(app_constant("kRelayUdpPort"), bicep_default(main, "udpPort"))

    def test_the_label_formula_is_what_the_apps_assume(self):
        # prod: <namePrefix><suffix>; any other environment: <namePrefix>-<environment><suffix>. The app's development infix is "-dev".
        formula = re.search(r"^var dnsNameLabel = (.+)$", read(MAIN_BICEP), re.MULTILINE)
        self.assertIsNotNone(formula)
        self.assertEqual(
            " ".join(formula.group(1).split()),
            "environmentName == 'prod' ? '${namePrefix}${dnsLabelSuffix}' : '${namePrefix}-${environmentName}${dnsLabelSuffix}'")
        self.assertEqual(app_constant("kRelayDevelopmentInfix"), "-dev")
        allowed = re.search(r"@allowed\(\[\s*'([^']+)'\s*'([^']+)'\s*\]\)\s*param environmentName", read(MAIN_BICEP))
        self.assertIsNotNone(allowed)
        self.assertEqual({allowed.group(1), allowed.group(2)}, {"dev", "prod"})


if __name__ == "__main__":
    unittest.main()
