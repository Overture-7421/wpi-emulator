#include "wpiemu/core/launcher/init_script.h"

namespace wpiemu::core::launcher {

std::string generateInitScript() {
    return R"groovy(// Generated by wpi-emulator (ADR 0003). Passed with -I on the command line only; the robot project is never modified.
// Loads the emulator's HALSim extension instead of the stock Sim GUI.
def emuExt = System.getenv('WPIEMU_EXT')              // absolute path of halsim_wpiemu.{dll,so,dylib}
if (emuExt == null || emuExt.trim().isEmpty()) {
    throw new GradleException('wpi-emulator: WPIEMU_EXT is not set')
}

allprojects { p ->
    p.afterEvaluate {
        def wpi = p.extensions.findByName('wpi')
        if (wpi == null) return
        // GradleRIO overwrites HALSIM_EXTENSIONS whenever one of its extensions is defaultEnabled
        wpi.sim.halExtensions.each { it.defaultEnabled.set(false) }
        p.tasks.matching {
            def n = it.class.name   // decorated class names carry a suffix -> startsWith
            n.startsWith('edu.wpi.first.gradlerio.simulation.JavaSimulationTask') ||
            n.startsWith('edu.wpi.first.gradlerio.simulation.NativeSimulationTask')
        }.configureEach { t -> t.environment('HALSIM_EXTENSIONS', emuExt) }
    }
}
)groovy";
}

}  // namespace wpiemu::core::launcher
