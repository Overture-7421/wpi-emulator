class WikiError(ValueError):
    """An actionable export or publication failure."""


def git(root: Path, *args: str) -> str:
    result = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True,
                            encoding="utf-8", env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
    if result.returncode:
        # Do not echo commands, stderr, remote URLs or credentials from Git failures.
        raise WikiError(f"git {args[0]} failed; check repository access, credentials and branch state")
    return result.stdout.strip()


def source_inventory(root: Path) -> set[str]:
    names = git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard").split("\0")
    return {name for name in names if name and (root / name).is_file() and (
        name == "README.md" or name.startswith("docs/") and name.endswith(".md")
        or name == "packaging/README.md"
        or name.startswith(("samples/", "plugins/_template/")) and name.endswith("/README.md"))}


def masked(text: str) -> str:
    """Keep offsets, but hide code so example destinations are never rewritten."""
    lines, fence = [], ""
    for line in text.splitlines(keepends=True):
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})(.*?)(?:\r?\n)?$", line)
        code = bool(fence) or line.startswith(("    ", "\t"))
        if marker:
            ticks, tail = marker.groups()
            code = True
            if not fence:
                fence = ticks
            elif ticks[0] == fence[0] and len(ticks) >= len(fence) and not tail.strip():
                fence = ""
        lines.append(re.sub(r"[^\r\n]", " ", line) if code else line)
    plain = "".join(lines)
    return re.sub(r"(`+)(?!`)([\s\S]*?)(?<!`)\1(?!`)",
                  lambda m: re.sub(r"[^\r\n]", " ", m[0]), plain)


def destinations(text: str) -> list[tuple[int, int, bool]]:
    """Locate destinations, not entire links, retaining titles and original formatting."""
    plain = masked(text)
    found = []
    image_references = {" ".join((m[2] or m[1]).lower().split()) for m in re.finditer(
        r"!\[([^\]\n]+)\](?:\[([^\]\n]*)\])?", plain)}
    for match in re.finditer(r"(?m)^ {0,3}\[([^\]\n]+)\]:[ \t]*(<[^>\n]+>|[^\s]+)", plain):
        start, end = match.span(2)
        if plain[start] == "<":
            start, end = start + 1, end - 1
        found.append((start, end, " ".join(match[1].lower().split()) in image_references))
    for match in re.finditer(r"(!?)\[(?:\\.|[^\]\\\n]|\[[^\]\n]*\])*\]\([ \t]*", plain):
        start = match.end()
        if start >= len(plain):
            raise WikiError("unterminated Markdown destination")
        if plain[start] == "<":
            end = plain.find(">", start + 1)
            if end < 0:
                raise WikiError("unterminated angle-bracket destination")
            found.append((start + 1, end, bool(match[1])))
            continue
        end, depth = start, 0
        while end < len(plain):
            char = plain[end]
            if char == "\\" and end + 1 < len(plain):
                end += 2
                continue
            if char == "(":
                depth += 1
            elif char == ")":
                if not depth:
                    break
                depth -= 1
            elif char.isspace() and not depth:
                break
            end += 1
        found.append((start, end, bool(match[1])))
    for match in re.finditer(r"""\b(href|src)\s*=\s*(["'])(.*?)\2""", plain, re.IGNORECASE):
        found.append((*match.span(3), match[1].lower() == "src"))
    # Full/collapsed references must resolve; shortcut references are ordinary prose if undefined.
    definitions = {" ".join(m[1].lower().split()) for m in re.finditer(
        r"(?m)^ {0,3}\[([^\]\n]+)\]:", plain)}
    for match in re.finditer(r"!?\[([^\]\n]+)\]\[([^\]\n]*)\]", plain):
        if " ".join((match[2] or match[1]).lower().split()) not in definitions:
            raise WikiError(f"undefined Markdown reference: {match[2] or match[1]}")
    return sorted(set(found))


def validate_mapping(root: Path, pages: dict[str, str], inventory: set[str]) -> None:
    folded = set()
    for source, page in pages.items():
        path = root / source
        if not path.resolve().is_relative_to(root) or not path.is_file() or path.is_symlink():
            raise WikiError(f"missing or unsafe mapped page: {source}")
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]*", page):
            raise WikiError(f"unsafe Wiki page name: {page}")
        if page.casefold() in folded or page.casefold() in {"_sidebar", "_footer"}:
            raise WikiError(f"Wiki page name collision: {page}")
        folded.add(page.casefold())
    omitted = inventory - pages.keys()
    if omitted:
        raise WikiError("unmapped first-party Markdown: " + ", ".join(sorted(omitted)))


def generate(root: Path, revision: str, repository: str, pages: dict[str, str] | None = None,
             inventory: set[str] | None = None) -> dict[str, bytes]:
    root = root.resolve()
    pages = PAGES if pages is None else pages
    if not re.fullmatch(r"[0-9a-f]{40,64}", revision):
        raise WikiError("source revision must be a full Git commit SHA")
    if not re.fullmatch(r"https://github\.com/[\w.-]+/[\w.-]+", repository):
        raise WikiError("repository must be a credential-free https://github.com/owner/repository URL")
    validate_mapping(root, pages, source_inventory(root) if inventory is None else inventory)
    texts = {source: (root / source).read_text(encoding="utf-8") for source in pages}
    headings = {source: check_docs.anchors(text) for source, text in texts.items()}

    def rewrite(source: str, value: str, image: bool) -> str:
        original = value
        value = html.unescape(re.sub(r"\\([\\()[\] ])", r"\1", value))
        parsed = urlsplit(value)
        if parsed.scheme == "file" or re.match(r"^[A-Za-z]:[/\\]", value) or "\\" in parsed.path:
            raise WikiError(f"{source}: unsupported local URL: {value}; use repository-relative paths")
        if parsed.scheme or parsed.netloc:
            return original
        target = ((root / unquote(parsed.path).lstrip("/")) if parsed.path.startswith("/")
                  else (root / source).parent / unquote(parsed.path)).resolve() if parsed.path else root / source
        if not target.is_relative_to(root) or not target.exists() or target.is_symlink():
            raise WikiError(f"{source}: missing or unsafe local target: {value}")
        relative = target.relative_to(root).as_posix()
        anchor_target = target / "README.md" if target.is_dir() else target
        if parsed.fragment and anchor_target.suffix == ".md":
            anchor_source = anchor_target.relative_to(root).as_posix()
            anchors = headings.get(anchor_source)
            if anchors is None and anchor_target.is_file():
                anchors = check_docs.anchors(anchor_target.read_text(encoding="utf-8"))
            if unquote(parsed.fragment) not in (anchors or set()):
                raise WikiError(f"{source}: missing anchor: {value}")
        if relative in pages and not image:
            path = quote(pages[relative], safe="-")
        else:
            kind = "tree" if target.is_dir() else "blob"
            path = f"{repository}/{kind}/{revision}/{quote(relative, safe='/')}"
            if image:
                # GitHub's raw media view, retaining an existing query string.
                query = parsed.query + ("&" if parsed.query else "") + "raw=true"
                return urlunsplit(("", "", path, query, parsed.fragment))
        return urlunsplit(("", "", path, parsed.query, parsed.fragment))

    output = {}
    for source, page in pages.items():
        text = texts[source]
        for start, end, image in reversed(destinations(text)):
            text = text[:start] + rewrite(source, text[start:end], image) + text[end:]
        canonical = f"{repository}/blob/{revision}/{quote(source, safe='/')}"
        prefix = f"{MARKER}\n> Generated from [{source}]({canonical}) at `{revision}`.\n\n"
        output[page + ".md"] = (prefix + text + ("" if text.endswith("\n") else "\n")).encode("utf-8")
    sidebar = MARKER
    available = set(pages.values())
    for group, members in NAVIGATION.items():
        links = [f"- [{page.replace('-', ' ')}]({quote(page)})" for page in members
                 if page in available]
        if links:
            sidebar += f"\n### {group}\n\n" + "\n".join(links) + "\n"
    edit_page = pages.get("docs/guides/documentation.md", pages.get("docs/README.md", "Home"))
    footer = (MARKER + f"\n[Canonical documentation]({repository}/blob/{revision}/docs/README.md)"
              f" · [Source revision]({repository}/commit/{revision})"
              f" · [Editing and publication]({edit_page})\n")
    output["_Sidebar.md"] = sidebar.encode("utf-8")
    output["_Footer.md"] = footer.encode("utf-8")
    manifest = {"owner": OWNER, "revision": revision, "repository": repository,
                "files": {name: hashlib.sha256(data).hexdigest()
                          for name, data in sorted(output.items())}}
    output[MANIFEST] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return output


def apply(output: Path, files: dict[str, bytes], dry_run: bool = False) -> list[str]:
    """Preflight everything before taking ownership; never delete an unowned file."""
    if output.is_symlink():
        raise WikiError("output must not be a symlink")
    previous = {}
    manifest_path = output / MANIFEST
    if manifest_path.is_symlink():
        raise WikiError("refusing symlink ownership manifest")
    if manifest_path.exists():
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            if manifest["owner"] != OWNER:
                raise ValueError("wrong owner")
            incoming = json.loads(files[MANIFEST])
            if manifest["repository"] != incoming["repository"]:
                raise ValueError("different source repository")
            if not re.fullmatch(r"[0-9a-f]{40,64}", manifest["revision"]):
                raise ValueError("invalid revision")
            previous = manifest["files"]
            if not isinstance(previous, dict):
                raise ValueError("invalid file list")
            for name, digest in previous.items():
                if not re.fullmatch(r"[A-Za-z0-9_-]+\.md", name) or not re.fullmatch(
                        r"[0-9a-f]{64}", digest):
                    raise ValueError("unsafe file entry")
        except (KeyError, ValueError, TypeError) as error:
            raise WikiError("invalid Wiki ownership manifest; restore it from Git history") from error
    existing = {path.name.casefold(): path for path in output.iterdir()} if output.exists() else {}
    for name in set(previous) | set(files):
        path = output / name
        if path.is_symlink():
            raise WikiError(f"refusing symlink: {name}")
        if name in previous and path.exists():
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != previous[name]:
                raise WikiError(f"owned Wiki file edited outside exporter: {name}; restore or reconcile it")
        if name != MANIFEST and name not in previous:
            collision = existing.get(name.casefold())
            # Wiki titles collide across supported markup extensions, not just Markdown.
            title_collision = next((p for p in existing.values()
                                    if p.stem.casefold() == path.stem.casefold()
                                    and p.suffix.lower() in {".md", ".markdown", ".rst", ".textile",
                                                            ".mediawiki", ".org", ".asciidoc"}), None)
            if collision or title_collision:
                raise WikiError(f"unmanaged Wiki collision: {name}; rename the existing page first")
    changes = ["delete " + name for name in sorted(previous.keys() - files.keys())
               if (output / name).exists()]
    changes += ["write " + name for name, data in sorted(files.items())
                if not (output / name).exists() or (output / name).read_bytes() != data]
    if not dry_run:
        output.mkdir(parents=True, exist_ok=True)
        for name in previous.keys() - files.keys():
            (output / name).unlink(missing_ok=True)
        for name, data in sorted(files.items()):
            if not (output / name).exists() or (output / name).read_bytes() != data:
                (output / name).write_bytes(data)
    return changes


def remote_head(root: Path, remote: str, branch: str) -> str:
    lines = git(root, "ls-remote", remote, "refs/heads/" + branch).splitlines()
    if len(lines) != 1:
        raise WikiError("source branch is missing or ambiguous")
    return lines[0].split()[0]


def publish(root: Path, files: dict[str, bytes], revision: str, remote: str, worktree: Path,
            source_remote: str = "origin", source_branch: str = "main",
            session: str = "github-actions") -> str:
    parsed_remote = urlsplit(remote)
    if parsed_remote.username or parsed_remote.password or parsed_remote.query or parsed_remote.fragment:
        raise WikiError("Wiki remote must not contain credentials; use an environment credential helper")
    if (parsed_remote.scheme and parsed_remote.scheme not in {"https", "file"}
            and not Path(remote).is_absolute()):
        raise WikiError("Wiki remote must use HTTPS or a local disposable repository")
    if worktree == root or root.is_relative_to(worktree):
        raise WikiError("Wiki worktree must not contain the source checkout")
    if git(root, "rev-parse", "HEAD") != revision or git(root, "status", "--porcelain"):
        raise WikiError("publication requires a clean checkout at the source revision")
    if remote_head(root, source_remote, source_branch) != revision:
        raise WikiError("stale source revision; rerun publication from current main")
    if worktree.exists() and any(worktree.iterdir()):
        raise WikiError("Wiki worktree must be absent or empty; use a fresh build directory")
    try:
        discovery = git(root, "ls-remote", "--symref", remote, "HEAD")
    except WikiError as error:
        raise WikiError("Wiki unavailable; enable Wiki, create its initial page and verify "
                        "WIKI_PUBLISH_TOKEN access (see docs/guides/documentation.md)") from error
    match = re.search(r"^ref: refs/heads/([^\s]+)\s+HEAD$", discovery, re.MULTILINE)
    if not match:
        raise WikiError("Wiki has no default branch; enable Wiki and create its initial page on GitHub")
    branch = match[1]
    worktree.parent.mkdir(parents=True, exist_ok=True)
    git(root, "clone", "--quiet", "--config", "core.autocrlf=false",
        "--single-branch", "--branch", branch, "--", remote, str(worktree))
    changes = apply(worktree, files)
    if not changes:
        return "Wiki already up to date"
    paths = [change.split(" ", 1)[1] for change in changes]
    git(worktree, "add", "--", *paths)
    if not re.fullmatch(r"[A-Za-z0-9_.:/-]+", session):
        raise WikiError("invalid publication session identifier")
    message = (f"docs: mirror source {revision}\n\n"
               "Co-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>\n"
               f"Copilot-Session: {session}\n")
    git(worktree, "-c", "user.name=WPI Emulator Wiki", "-c",
        "user.email=41898282+github-actions[bot]@users.noreply.github.com", "commit", "--quiet", "-m", message)
    if remote_head(root, source_remote, source_branch) != revision:
        raise WikiError("source advanced during publication; no Wiki push made, rerun from main")
    git(worktree, "push", "--quiet", "origin", f"HEAD:refs/heads/{branch}")
    return f"Published Wiki from {revision}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--repository", default="https://github.com/Overture-7421/wpi-emulator")
    parser.add_argument("--revision", default="HEAD")
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--publish", action="store_true")
    parser.add_argument("--wiki-remote")
    parser.add_argument("--wiki-worktree", type=Path)
    parser.add_argument("--source-remote", default="origin")
    parser.add_argument("--source-branch", default="main")
    parser.add_argument("--session", default="github-actions")
    args = parser.parse_args()
    try:
        if args.output.is_symlink():
            raise WikiError("output must not be a symlink")
        root, output = args.root.resolve(), args.output.resolve()
        # Generated files may not overwrite canonical source, even with --dry-run.
        protected = [root / source for source in PAGES]
        if output == root or root.is_relative_to(output) or any(
                path.is_relative_to(output) for path in protected):
            raise WikiError("output overlaps canonical documentation")
        revision = git(root, "rev-parse", "--verify", args.revision + "^{commit}")
        if revision != git(root, "rev-parse", "HEAD"):
            raise WikiError("revision must match checkout HEAD; check out the requested commit first")
        files = generate(root, revision, args.repository.rstrip("/"))
        changes = apply(output, files, args.dry_run)
        print(f"Wiki {'dry-run' if args.dry_run else 'preview'}: {len(files)} files; {len(changes)} changes")
        if args.publish:
            if args.dry_run or not args.wiki_remote or not args.wiki_worktree:
                raise WikiError("--publish requires --wiki-remote and --wiki-worktree, without --dry-run")
            print(publish(root, files, revision, args.wiki_remote, args.wiki_worktree.resolve(),
                          args.source_remote, args.source_branch, args.session))
        return 0
    except (WikiError, OSError, UnicodeError) as error:
        print(f"wiki: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
